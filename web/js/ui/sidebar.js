const Sidebar = {
  render() {
    const nav = document.getElementById('sidebarNav');
    let html = '';
    SIDEBAR_NAV.forEach(group => {
      html += `<div class="nav-group"><div class="nav-group-title">${group.title}</div>`;
      group.items.forEach(item => {
        html += `<div class="nav-item" data-key="${item.key}" onclick="openNav('${item.key}')">
          <span class="nav-icon">${item.icon}</span>
          <span class="nav-label">${item.label}</span>
        </div>`;
      });
      html += '</div>';
    });
    nav.innerHTML = html;
  },

  setActive(key) {
    document.querySelectorAll('.nav-item').forEach(el => {
      el.classList.toggle('active', el.getAttribute('data-key') === key);
    });
  },
};

function openNav(key) {
  Router.navigate(key);
}

function toggleSidebar() {
  document.getElementById('sidebar').classList.toggle('collapsed');
}

function toggleTenantMenu(e) {
  e.stopPropagation();
  document.getElementById('tenantMenu').classList.toggle('open');
}

function toggleUserMenu(e) {
  e.stopPropagation();
  document.getElementById('userMenu').classList.toggle('open');
}

function logout() {
  State.clear();
  window.location.href = '/login.html';
}

// Close menus on outside click
document.addEventListener('click', () => {
  const tm = document.getElementById('tenantMenu');
  const um = document.getElementById('userMenu');
  if (tm) tm.classList.remove('open');
  if (um) um.classList.remove('open');
});
